/**
 * تمييز العدد: «١٩ ساعة» لا «١٩ ساعات».
 *
 * العربية تصرّف المعدود على أربع درجات، وأكثر التطبيقات تخلط بينها لأنها
 * تكتفي بصيغتين: مفردٍ وجمع. والقارئ يلحظ الخلل ولو ما سمّاه — «١٩ ساعات»
 * تُقرأ ركيكة، و«٣ ساعة» أركّ.
 *
 *   الواحد          ساعة        (بلا رقم — الرقمُ فيه فضول)
 *   الاثنان         ساعتين
 *   من ٣ إلى ١٠     ٣ ساعات      (جمع القِلّة)
 *   من ١١ فما فوق   ١٩ ساعة      (مفردٌ منصوب)
 *
 * والمئات ترجع إلى آخر عددها: «١٠٣ ساعات» صحيحة لأن آخرها ثلاثة.
 *
 * والمثنّى نكتبه بالياء («ساعتين» لا «ساعتان») لأن كل مواضعه في التطبيق بعد
 * حرفٍ أو في موضع نصبٍ أو جرّ: «قبل ساعتين»، «باقي ساعتين»، «حذفتَ يومين».
 */

/** الصيغ الأربع لكل معدود: [الواحد، الاثنان، من ٣ إلى ١٠، ما فوقها]. */
export const UNITS = {
  minute: ['دقيقة', 'دقيقتين', 'دقائق', 'دقيقة'],
  hour: ['ساعة', 'ساعتين', 'ساعات', 'ساعة'],
  day: ['يوم', 'يومين', 'أيام', 'يومًا'],
  week: ['أسبوع', 'أسبوعين', 'أسابيع', 'أسبوعًا'],
  month: ['شهر', 'شهرين', 'أشهر', 'شهرًا'],
  friday: ['جمعة', 'جمعتين', 'جمع', 'جمعة'],
  student: ['طالب', 'طالبين', 'طلاب', 'طالبًا'],
  signup: ['تسجيل', 'تسجيلين', 'تسجيلات', 'تسجيلًا'],
  record: ['سجل', 'سجلين', 'سجلات', 'سجلًّا'],
  photo: ['صورة', 'صورتين', 'صور', 'صورة'],
  time: ['مرة', 'مرتين', 'مرات', 'مرة'],
  link: ['رابط', 'رابطين', 'روابط', 'رابطًا'],
  move: ['حركة', 'حركتين', 'حركات', 'حركة'],
  amount: ['مبلغ', 'مبلغين', 'مبالغ', 'مبلغًا'],
  ledger: ['دفتر', 'دفترين', 'دفاتر', 'دفترًا'],
  number: ['رقم', 'رقمين', 'أرقام', 'رقمًا'],
  member: ['مشترك', 'مشتركين', 'مشتركين', 'مشتركًا'],
  season: ['موسم', 'موسمين', 'مواسم', 'موسمًا'],
  part: ['جزء', 'جزأين', 'أجزاء', 'جزءًا'],
  face: ['وجه', 'وجهين', 'أوجه', 'وجهًا'],
};

/**
 * «ساعة» · «ساعتين» · «٣ ساعات» · «١٩ ساعة».
 *
 * يقبل اسم وحدةٍ من الجدول فوق، أو أربع صيغٍ مكتوبةً كما هي لمعدودٍ ما دخل
 * الجدول.
 */
export const say = (n, unit) => {
  const forms = Array.isArray(unit) ? unit : UNITS[unit];
  if (!forms) return String(n);
  const c = Math.abs(Math.round(Number(n) || 0));
  const [one, two, few, many] = forms;
  if (c === 1) return one;
  if (c === 2) return two;
  const tail = c % 100;
  // الآلاف تُفصل بفاصلة: «١٬٥٣٢ تسجيلًا» تُقرأ بلمحة، وبلا فاصلةٍ تُعدّ خاناتُها
  return `${c.toLocaleString('en-US')} ${tail >= 3 && tail <= 10 ? few : many}`;
};
