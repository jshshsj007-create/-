/**
 * من يقرأ ومن يكتب.
 *
 * قاعدةٌ واحدة يقرأها الطرفان: الجوال ليخفي الأزرار، والخادم ليردّ الحفظ.
 * ولو كُتبت مرتين تفرّقتا يومًا — فيُخفي الجوال زرًّا يقبله الخادم، أو يمنع
 * الخادمُ عملًا يُظهره الجوال. وهذا ملفُّها.
 */

/** المدير يملك كل شيء، فلا تُعدّ له صلاحيات. */
export const isAdmin = (u) => u?.role === 'مدير';

/** هل يفتح هذا القسم؟ */
export const allowed = (u, perm) => isAdmin(u) || (u?.permissions || []).includes(perm);

/**
 * هل يكتب فيه؟
 *
 * صلاحيةٌ تفتح الشاشة، و«يشوف فقط» تمنع القلم والسلة وأزرار الإضافة.
 * وإخفاء الأزرار في الجوال زينةٌ لا حراسة: من فتح جهازه وأعاد الزر وصل
 * حفظُه. فالمنع الحقيقي في الخادم — تُرَدّ البيانات كما كانت.
 *
 * والمدير لا يُقيَّد: من ملك «المستخدمون والصلاحيات» ملك تبديل هذا كله،
 * فتقييده وهمٌ يزول بضغطتين.
 */
export const canWrite = (u, perm) =>
  allowed(u, perm) && (isAdmin(u) || !(u?.readOnly || []).includes(perm));

/**
 * صلاحيةُ قراءة تقارير اليوم.
 *
 * غيرُ كتابتها: من يقف مع الأولاد يُطالَب بتقريره (`mustReport`)، وهذي تُعطى
 * لمن تريد أن يقرأ ما كتبه الفريق — نائبُك أو مسؤولُ الجودة. ولا تفتح له
 * شيئًا غيرها: لا برامجَ ولا مشتركين ولا مالًا.
 *
 * والمديرُ يقرؤها بلا إعطاء، فهو من يسأل عنها أصلًا.
 */
export const READ_REPORTS = 'قراءة تقارير اليوم';
export const readsReports = (u) => allowed(u, READ_REPORTS);
